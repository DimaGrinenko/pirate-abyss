/** Official Engine social-mode restricted phrases, checked 2026-10-01.
 * Include common plurals and joined payout/paytable spellings. Only visible
 * copy is checked; protocol mode IDs, API amounts and currency codes are not.
 * https://engine.io/docs/reference/social-mode */
export function hasRestrictedSocialTerms(text: string): boolean {
  return /\b(?:bets?|bet\/s|betting|bought|buy(?:ing)?|cash|(?:at\s+the\s+)?cost\s+of|credits?|currenc(?:y|ies)|deposits?|gambl(?:e|es|ing)|loss\s+(?:limit|streak)|money|paid|pay(?:s|ers?|outs?|tables?)?|profit|purchas(?:e|es|ed|ing)|rebet|stakes?|wager(?:s|ed|ing)?|win\s+feature|withdraw(?:s|ing)?|be\s+awarded\s+to\s+player['’]s\s+accounts|funds)\b/i.test(text);
}
/** Keep protocol errors unchanged internally; translate only their visible message. */
export function localizeMessage(message: string, selected: Language = language, social = socialMode): string {
  if (Object.hasOwn(english, message)) return translate(message as TranslationKey, selected, {}, social);
  // An already localized server error may be encountered again after recovery.
  // Resolve exact dictionary entries without editing identifiers or parameters.
  if (social) {
    const entry = (Object.entries(english) as [TranslationKey, string][]).find(([, text]) => text === message);
    if (entry) return translate(entry[0], selected, {}, true);
    if (hasRestrictedSocialTerms(message)) return translate('Не удалось выполнить запрос. Проверьте состояние сессии.', 'en', {}, true);
  }
  return (selected === 'en' || social) && /[А-Яа-яЁё]/.test(message) ? translate('Не удалось выполнить запрос. Проверьте состояние сессии.', 'en', {}, social) : message;
}

