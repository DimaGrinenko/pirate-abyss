/** Launch locale is ready before React renders; authentication may require social copy. */
export type Language = 'ru' | 'en';
export function resolveLanguage(search: string): Language {
  const params = new URLSearchParams(search);
  for (const key of ['lang', 'language']) {
    const value = params.get(key)?.trim().toLowerCase();
    if (value === 'en' || value === 'ru') return value;
  }
  return 'en';
}
const launchSearch = typeof window === 'undefined' ? '' : window.location.search;
export function resolveDisplayLocale(search: string, socialCasino?: boolean): { language: Language; social: boolean } {
  // A URL may opt into social presentation, but cannot override the server's
  // authenticated requirement. Never infer financial behaviour from this flag.
  const social = socialCasino === true || new URLSearchParams(search).get('social')?.trim().toLowerCase() === 'true';
  return { language: social ? 'en' : resolveLanguage(search), social };
}
