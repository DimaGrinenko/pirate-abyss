type Parameters = Record<string, string | number>;
export function translate(key: TranslationKey, selected: Language, params: Parameters = {}, social = false): string {
  const text: string = social ? socialEnglish[key] ?? english[key] : selected === 'en' ? english[key] : key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name: string) => params[name] === undefined ? placeholder : String(params[name]));
}
export function t(key: TranslationKey, params?: Parameters): string { return translate(key, language, params, socialMode); }
/** Call before syncSession's React state update, so every child receives the
 * authenticated locale on its next render. Idempotent; no DOM text rewriting. */
export function configureSessionLocale(socialCasino?: boolean, search = launchSearch): boolean {
  const next = resolveDisplayLocale(search, socialCasino);
  if (next.language === language && next.social === socialMode) return false;
  language = next.language; socialMode = next.social;
  numberLocale = language === 'en' ? 'en-US' : 'ru-RU';
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = language;
    document.title = t('Пиратская бездна');
  }
  return true;
}
export function formatNumber(value: number, options: Intl.NumberFormatOptions = {}, selected: Language = language): string {
  return value.toLocaleString(selected === 'en' ? 'en-US' : 'ru-RU', options);
}
export function formatAmount(value: number, selected: Language = language): string { return formatNumber(value, { minimumFractionDigits: 2, maximumFractionDigits: 6 }, selected); }

